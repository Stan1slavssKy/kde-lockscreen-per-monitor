#!/usr/bin/env bash
# Different lock screen wallpaper on each monitor — KDE Plasma 5 (X11)
#
# Usage:
#   bash lockscreen-per-monitor.sh
#
# The script lists your monitors and asks for an image path for each one.
# Tab completion works; you can also drag a file from Dolphin into the terminal.
# Leave a path empty to skip a monitor — it will use the first image you entered.

set -euo pipefail

PLUGIN_ID="org.kde.perscreenimage"
DIR="$HOME/.local/share/plasma/wallpapers/$PLUGIN_ID"

# Collect monitors: name and resolution, e.g. "DP-1 2560x1440"
mapfile -t MONITORS < <(
  xrandr --listmonitors 2>/dev/null | tail -n +2 |
    awk '{ geo=$3; gsub(/\/[0-9]+/, "", geo); sub(/\+.*/, "", geo); print $NF, geo }'
)

if [ ${#MONITORS[@]} -eq 0 ]; then
  echo "No monitors found (is xrandr installed and are you in an X11 session?)."
  exit 1
fi

clean_path() {
  local p="$1"
  p="${p#"${p%%[![:space:]]*}"}"          # trim leading spaces
  p="${p%"${p##*[![:space:]]}"}"          # trim trailing spaces
  p="${p#\'}"; p="${p%\'}"                # strip single quotes (drag and drop)
  p="${p#\"}"; p="${p%\"}"                # strip double quotes
  p="${p#file://}"                        # strip file:// prefix
  p="${p/#\~/$HOME}"                      # expand ~
  printf '%s' "$p"
}

echo "Found ${#MONITORS[@]} monitor(s)."
echo

map=""
fallback=""
for entry in "${MONITORS[@]}"; do
  name="${entry%% *}"
  res="${entry#* }"
  while true; do
    read -r -e -p "Image for $name ($res), empty to skip: " input
    img="$(clean_path "$input")"
    if [ -z "$img" ]; then
      echo "  Skipped $name."
      break
    fi
    if [ -f "$img" ]; then
      img="$(readlink -f "$img")"
      esc="${img//\\/\\\\}"; esc="${esc//\"/\\\"}"
      map+="        \"$name\": \"file://$esc\","$'\n'
      [ -z "$fallback" ] && fallback="file://$esc"
      break
    fi
    echo "  File not found: $img — try again."
  done
done

if [ -z "$fallback" ]; then
  echo "No images given, nothing to do."
  exit 1
fi

mkdir -p "$DIR/contents/ui"

cat > "$DIR/metadata.desktop" <<EOF
[Desktop Entry]
Name=Image per screen
Type=Service
Icon=preferences-desktop-wallpaper
X-KDE-ServiceTypes=Plasma/Wallpaper
X-KDE-PluginInfo-Name=$PLUGIN_ID
X-KDE-PluginInfo-Version=1.0
X-KDE-PluginInfo-License=GPL
X-KDE-PluginInfo-EnabledByDefault=true
X-Plasma-API=declarativeappletscript
X-Plasma-MainScript=ui/main.qml
EOF

cat > "$DIR/contents/ui/main.qml" <<EOF
import QtQuick 2.15
import QtQuick.Window 2.15

Rectangle {
    id: root
    color: "black"

    // Monitor name -> image (generated by the script, safe to edit by hand)
    readonly property var images: ({
$map    })
    readonly property string fallback: "$fallback"

    Image {
        anchors.fill: parent
        fillMode: Image.PreserveAspectCrop
        source: root.images[Screen.name] || root.fallback
        asynchronous: true
        smooth: true
        sourceSize.width: root.width
        sourceSize.height: root.height
    }
}
EOF

kbuildsycoca5 >/dev/null 2>&1 || true

echo
echo "Done: $DIR"
echo
echo "Next: System Settings -> Screen Locking -> Appearance: Configure..."
echo "  Wallpaper type: \"Image per screen\" -> Apply."
echo
echo "Test without locking (close with your password):"
echo "  /usr/lib/x86_64-linux-gnu/libexec/kscreenlocker_greet --testing"
